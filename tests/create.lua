vim.opt.runtimepath:prepend(vim.fn.getcwd())
vim.cmd.runtime('plugin/fujutsu.lua')
local dir = vim.fn.tempname()
vim.fn.mkdir(dir, 'p')
local function jj(args)
  local r = vim.system(vim.list_extend({ 'jj', '--no-pager', '--color=never' }, args), { cwd = dir, text = true }):wait()
  assert(r.code == 0, r.stderr)
  return vim.trim(r.stdout)
end
local function id(rev, template) return jj({ 'log', '--no-graph', '-r', rev, '-T', template or 'commit_id' }) end
jj({ 'git', 'init' })
jj({ 'config', 'set', '--repo', 'user.name', 'Test' })
jj({ 'config', 'set', '--repo', 'user.email', 'test@example.com' })
jj({ 'describe', '-m', 'base' })
vim.fn.writefile({ 'base' }, dir .. '/file')
jj({ 'bookmark', 'create', 'base' })
jj({ 'new', '-m', 'child' })
jj({ 'bookmark', 'create', 'child' })
vim.cmd.cd(dir)
vim.cmd([[J log -r 'all()']])
local buf = vim.api.nvim_get_current_buf()
local log = require('fujutsu').log(buf)
local function focus(rev)
  vim.api.nvim_set_current_buf(buf); log.refresh(buf)
  local commit = id(rev)
  for i, row in pairs(log.rows) do
    if row.id == commit and row.first == i then vim.api.nvim_win_set_cursor(0, { i, 0 }); return end
  end
  error('Missing commit')
end
local function create(key, rev)
  focus(rev)
  local job = require('fujutsu.actions').create(log, buf, dir, require('fujutsu.selection').capture(log, false), key)
  assert(vim.wait(10000, function() return job.result ~= nil end, 20))
  assert(job.result.code == 0, job.result.stderr)
end
create('gn', 'base')
assert(id('parents(@)') == id('base'))
assert(id('parents(child)') == id('@'))
assert(vim.b.fujutsu_file.description)
local wc = id('@', 'change_id')
create('gN', 'base')
assert(id('@', 'change_id') == wc)
assert(id('parents(parents(base))') == id('root()'))
create('ge', 'child')
assert(id('@') == id('child'))
-- Guard real unsaved buffers before a working-copy switch.
vim.cmd.edit(dir .. '/file')
vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'unsaved' })
local ok = pcall(require('fujutsu.runner').guard, dir)
assert(not ok)
vim.bo.modified = false
print('PASS: child insertion edits new commit, parent insertion preserves @, ge and unsaved-buffer guard')
vim.cmd.cd('/')
vim.fn.delete(dir, 'rf')
vim.cmd.qa({ bang = true })
